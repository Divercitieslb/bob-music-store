# -*- coding: utf-8 -*-
"""Turn newset_keyboards.P into a Shopify import CSV and the collection rows.

Matches the 33 columns of import/bob-music-products.csv exactly, so the two can
be imported the same way (or concatenated).

TWO THINGS THAT HAVE BITTEN THIS STORE BEFORE AND ARE HANDLED HERE:

  1. The image URL in the original CSV still says YOUR-GITHUB-USERNAME and
     @main. Neither is right: the images live on the CATALOGUE branch, and the
     account is Divercitieslb. Verified — jsDelivr answers 200 for
     @catalogue/import/images/ACC-01-01.jpg and 404 for the placeholder.

  2. A collection's handle must equal Shopify's own handleize(title), or
     Shopify generates a different one and every link in the theme 404s. The
     handles here are generated by that same function rather than typed.
"""
import csv, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from newset_keyboards import P, NEW_COLLECTIONS           # noqa: E402

REPO = 'Divercitieslb/bob-music-store'
BRANCH = 'catalogue'
CDN = f'https://cdn.jsdelivr.net/gh/{REPO}@{BRANCH}/import/images/'

COLS = ['Handle', 'Title', 'Body (HTML)', 'Vendor', 'Product Category', 'Type',
        'Tags', 'Published', 'Option1 Name', 'Option1 Value', 'Option2 Name',
        'Option2 Value', 'Option3 Name', 'Option3 Value', 'Variant SKU',
        'Variant Grams', 'Variant Inventory Tracker', 'Variant Inventory Qty',
        'Variant Inventory Policy', 'Variant Fulfillment Service',
        'Variant Price', 'Variant Compare At Price', 'Variant Requires Shipping',
        'Variant Taxable', 'Variant Barcode', 'Image Src', 'Image Position',
        'Image Alt Text', 'Gift Card', 'SEO Title', 'SEO Description',
        'Variant Weight Unit', 'Status']

CATEGORY = {
    'Arranger Keyboard':   'Arts & Entertainment > Hobbies & Creative Arts > Musical Instruments > Pianos & Keyboards',
    'Keyboard Workstation':'Arts & Entertainment > Hobbies & Creative Arts > Musical Instruments > Pianos & Keyboards',
    'Synthesizer':         'Arts & Entertainment > Hobbies & Creative Arts > Musical Instruments > Pianos & Keyboards',
    'Electronic Keyboard': 'Arts & Entertainment > Hobbies & Creative Arts > Musical Instruments > Pianos & Keyboards',
    'MIDI Controller':     'Arts & Entertainment > Hobbies & Creative Arts > Musical Instruments > Electronic Musical Instruments',
    'Electric Guitar':     'Arts & Entertainment > Hobbies & Creative Arts > Musical Instruments > String Instruments > Guitars',
}


def handleize(title):
    """Shopify's own rule: lowercase, drop apostrophes, & -> space, the rest
    of the non-alphanumerics -> hyphen, collapse, trim."""
    s = title.lower().replace("'", '').replace('’', '')
    s = s.replace('&', ' ')
    s = re.sub(r'[^a-z0-9]+', '-', s)
    return re.sub(r'-+', '-', s).strip('-')


def body_html(p):
    out = [f'<p>{p["lede"]}</p>']
    out.append('<ul>')
    out += [f'  <li>{b}</li>' for b in p['bullets']]
    out.append('</ul>')
    out.append(f'<p><strong>Condition.</strong> {p["condition"]}</p>')
    if p.get('note'):
        out.append(f'<p>{p["note"]}</p>')
    out.append('<p>Every instrument is checked and set up on our bench before it '
               'leaves the shop. Ask us for the price and availability of this one '
               '— we answer WhatsApp within the hour during shop hours.</p>')
    return '\n'.join(out)


def seo_desc(p):
    s = re.sub(r'<[^>]+>', '', p['lede'])
    s = f'{s} Bob Music Store, Beirut.'
    return s[:320]


def rows_for(p):
    h = handleize(p['title'])
    imgs = [f'{p["sku"]}-{i+1:02d}.jpg' for i in range(len(p['photos']))]
    first = {c: '' for c in COLS}
    first.update({
        'Handle': h,
        'Title': p['title'],
        'Body (HTML)': body_html(p),
        'Vendor': p['vendor'],
        'Product Category': CATEGORY.get(p['type'], ''),
        'Type': p['type'],
        'Tags': ', '.join(p['tags']),
        'Published': 'true',
        'Option1 Name': 'Title',
        'Option1 Value': 'Default Title',
        'Variant SKU': p['sku'],
        'Variant Grams': str(p['grams']),
        'Variant Inventory Tracker': 'shopify',
        'Variant Inventory Qty': '1',
        'Variant Inventory Policy': 'deny',
        'Variant Fulfillment Service': 'manual',
        # Every product in this store is 0.00 and the theme shows "Price on
        # request" for it. Do NOT invent a number for second-hand gear.
        'Variant Price': '0.00',
        'Variant Requires Shipping': 'true',
        'Variant Taxable': 'true',
        'Image Src': CDN + imgs[0],
        'Image Position': '1',
        'Image Alt Text': f'{p["title"]} — Bob Music Store',
        'Gift Card': 'false',
        'SEO Title': p['title'][:70],
        'SEO Description': seo_desc(p),
        'Variant Weight Unit': 'g',
        'Status': 'active',
    })
    rows = [first]
    for i, fn in enumerate(imgs[1:], start=2):
        extra = {c: '' for c in COLS}
        extra.update({'Handle': h, 'Image Src': CDN + fn,
                      'Image Position': str(i),
                      'Image Alt Text': f'{p["title"]} — view {i}'})
        rows.append(extra)
    return rows


def main(outdir):
    os.makedirs(outdir, exist_ok=True)

    prod = os.path.join(outdir, 'keyboards-products.csv')
    n = 0
    with open(prod, 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=COLS)
        w.writeheader()
        for p in P:
            for r in rows_for(p):
                w.writerow(r); n += 1

    coll = os.path.join(outdir, 'keyboards-collections.csv')
    with open(coll, 'w', newline='', encoding='utf-8') as f:
        w = csv.writer(f)
        w.writerow(['Handle', 'Title', 'Body HTML', 'Sort Order', 'Published',
                    'Must Match', 'Rule: Product Column', 'Rule: Relation',
                    'Rule: Condition'])
        for title, handle, level, parent in NEW_COLLECTIONS:
            assert handle == handleize(title), f'{handle} != {handleize(title)}'
            w.writerow([handle, title, '', 'best-selling', 'TRUE', 'all',
                        'Tag', 'Equals', title])

    # what the photographs must be renamed to
    man = os.path.join(outdir, 'image-manifest.txt')
    with open(man, 'w', encoding='utf-8') as f:
        for p in P:
            for i, src in enumerate(p['photos']):
                f.write(f'{src}.jpg -> {p["sku"]}-{i+1:02d}.jpg   ({p["title"]})\n')

    print(f'{prod}\n  {n} rows for {len(P)} products')
    print(f'{coll}\n  {len(NEW_COLLECTIONS)} collections')
    print(f'{man}')
    print()
    for title, handle, level, parent in NEW_COLLECTIONS:
        print(f'  {"  " * (level - 1)}{title}  ->  /collections/{handle}')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '../import')
